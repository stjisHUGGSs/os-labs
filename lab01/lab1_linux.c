/*
 * ЛР №1, дополнительное задание (Linux / POSIX).
 *
 * Только системные вызовы read()/write()/open()/isatty() на дескрипторах —
 * без printf/scanf (у них свой буфер в пользовательском пространстве).
 *
 * Требования задания:
 *  - приглашение показывать, только если ввод идёт с консоли (stdin = терминал);
 *  - при "<input.txt" приглашения нет;
 *  - при ">out.txt" приглашение всё равно должно появиться на экране, а не в файле;
 *  - числа-дескрипторы не выводить.
 *
 * Сборка: gcc lab1_linux.c -o lab1_linux -Wall
 */
#include <fcntl.h>   /* open, O_WRONLY */
#include <string.h>  /* strlen */
#include <unistd.h>  /* read, write, close, isatty, STDIN_FILENO ... */

int main(void)
{
    char buf[256];

    /* Приглашение — только если дескриптор 0 это терминал.
     * isatty(0) != 0 -> ввод с клавиатуры; 0 -> stdin переадресован
     * на файл/канал ("<file", "|"), и приглашение не нужно. */
    if (isatty(STDIN_FILENO)) {
        const char *prompt = "Введите произвольный текст: ";

        /* Куда писать приглашение? НЕ в дескриптор 1: при "> out.txt"
         * он указывает на файл, и приглашение попало бы туда.
         *
         * Выбран /dev/tty — управляющий терминал процесса. Он не зависит
         * ни от одной переадресации, поэтому приглашение гарантированно
         * (принудительно) оказывается на экране.
         *
         * Альтернатива — stderr (дескриптор 2). Это стандартный приём
         * ("диагностика и подсказки не в stdout"), но он слабее: при
         * "2> err.txt" или "2>&1 > out.txt" приглашение снова уйдёт в файл.
         * stderr используем только как запасной вариант, если /dev/tty
         * открыть не удалось. */
        int out = open("/dev/tty", O_WRONLY);   /* открыть терминал на запись */
        if (out < 0)
            out = STDERR_FILENO;                /* запасной вариант */

        write(out, prompt, strlen(prompt));     /* вывести приглашение */

        if (out != STDERR_FILENO)
            close(out);                         /* свой дескриптор закрываем, чужой — нет */
    }

    /* Читаем из дескриптора 0 одним вызовом (для терминала — одну строку,
     * для файла — до sizeof(buf) байт). Возвращает число прочитанных байт,
     * 0 — конец файла, -1 — ошибка. */
    ssize_t n = read(STDIN_FILENO, buf, sizeof(buf));
    if (n < 0)
        return 1;

    /* Предуведомление — отдельным вызовом write() в stdout (дескриптор 1),
     * как в базовом варианте. Оно должно попасть в файл при ">out.txt". */
    const char *notice = "\nРанее введённый в программу текст:\n";
    write(STDOUT_FILENO, notice, strlen(notice));

    /* Выводим ровно столько байт, сколько прочитали. */
    write(STDOUT_FILENO, buf, (size_t)n);

    return 0;
}
